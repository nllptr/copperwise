"""Bundle unchanged production Lua into the isolated ticket-01 diagnostics."""
from hashlib import sha256
from pathlib import Path
import argparse

ROOT = Path(__file__).resolve().parents[2]
DEST = Path(__file__).resolve().parent / "addons/CopperwiseDiagnostics/Sources.lua"
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true", help="Fail if the bundle is stale")
args = parser.parse_args()
parts = ["-- Generated by probes/ticket-01/build.py; do not edit.\n"
         "local applyEnvironment = setfenv\nCopperwiseDiagnosticSources = {}\n"]
for name in ("Inventory", "Storage", "Scan"):
    source = (ROOT / f"addons/Copperwise/{name}.lua").read_text()
    parts.append(f'-- {name}.lua SHA256: {sha256(source.encode()).hexdigest()}\n'
                 f'CopperwiseDiagnosticSources.{name} = function(env)\n'
                 f'local run = function()\n{source}\nend\n'
                 f'applyEnvironment(run, env)\nreturn run()\nend\n')
bundle = "".join(parts)
if args.check:
    if not DEST.exists() or DEST.read_text() != bundle:
        raise SystemExit("Diagnostic bundle is stale; run python3 probes/ticket-01/build.py")
    print("Diagnostic bundle matches production sources")
else:
    DEST.write_text(bundle)
    print(f"Wrote {DEST.relative_to(ROOT)}")
